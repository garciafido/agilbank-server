/**
 * Fix PalJS DMMF generation for ts-node-dev compatibility.
 *
 * PalJS generates dmmf/index.ts with the entire DMMF as inline TypeScript (~4M lines).
 * ts-node-dev cannot transpile this. This script replaces it with a dynamic JSON loader.
 * The companion dmmf.json (generated alongside) is loaded at runtime via readFileSync.
 */
const fs = require('fs');
const path = require('path');

const dmmfDir = path.join(__dirname, '..', 'src', 'paljs-generated', 'dmmf');
const indexPath = path.join(dmmfDir, 'index.ts');
const jsonPath = path.join(dmmfDir, 'dmmf.json');

if (!fs.existsSync(jsonPath)) {
  console.log('⚠️  dmmf.json not found, skipping dmmf fix');
  process.exit(0);
}

const newContent = `// Generated by @paljs/generator - DO NOT EDIT
// Patched by fix-paljs-dmmf.js — dynamic JSON loading for ts-node-dev compatibility
import type { DMMF } from '@prisma/generator-helper';
import { readFileSync } from 'fs';
import { join } from 'path';

export const dmmf: DMMF.Document = JSON.parse(
  readFileSync(join(__dirname, 'dmmf.json'), 'utf-8')
);
`;

fs.writeFileSync(indexPath, newContent);
console.log('✅ Patched paljs dmmf/index.ts → dynamic JSON loading');
